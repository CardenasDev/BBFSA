-- Modelo basado en la matriz semanal "Evaluacion y reinduccion de labores
-- cultivo". Cada valor diario se conserva por empleado, labor y fecha.
-- El acumulado semanal NO se interpreta automaticamente como nota final:
-- puntaje, minimo y resultado se almacenan por separado y son configurables.

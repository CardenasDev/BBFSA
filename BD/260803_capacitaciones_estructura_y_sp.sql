-- FK diferida porque importaciones se crea despues de evaluaciones.
SET @FK_IMPORT_EVAL_EXISTE := (
    SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE CONSTRAINT_SCHEMA = DATABASE()
      AND TABLE_NAME = 'bbf_capacitacion_evaluaciones'
      AND CONSTRAINT_NAME = 'FK_BBF_CAP_EVAL_IMPORT'
);
SET @SQL_FK_IMPORT_EVAL := IF(
    @FK_IMPORT_EVAL_EXISTE = 0,
    'ALTER TABLE bbf_capacitacion_evaluaciones ADD KEY IDX_BBF_CAP_EVAL_IMPORT (ID_CAPACITACION_IMPORTACION), ADD CONSTRAINT FK_BBF_CAP_EVAL_IMPORT FOREIGN KEY (ID_CAPACITACION_IMPORTACION) REFERENCES bbf_capacitacion_importaciones (ID_CAPACITACION_IMPORTACION)',
    'SELECT 1'
);

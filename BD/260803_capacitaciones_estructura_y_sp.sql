    IN P_DOCUMENTO_RUTA VARCHAR(500), IN P_FIRMA_URL VARCHAR(500), IN P_OBSERVACIONES TEXT, IN P_ID_USUARIO INT
)
BEGIN
    DECLARE V_ESTADO VARCHAR(30); SET V_ESTADO=UPPER(TRIM(P_ESTADO));

    SELECT * FROM bbf_capacitacion_evaluaciones WHERE ID_CAPACITACION_PARTICIPANTE=P_ID_PARTICIPANTE AND ID_CAPACITACION_LABOR=P_ID_LABOR AND FECHA_EVALUACION=P_FECHA;

DROP PROCEDURE IF EXISTS `SP_BBF_CAPACITACION_ALERTAS_LISTAR`$$
CREATE PROCEDURE `SP_BBF_CAPACITACION_ALERTAS_LISTAR`(IN P_ID_EMPLEADO INT)
BEGIN
    SELECT 'EVALUACION_PENDIENTE' AS TIPO_ALERTA,P.ID_CAPACITACION_PARTICIPANTE,E.ID_EMPLEADO,E.NUMERO_DOCUMENTO,
    CONCAT_WS(' ',E.NOMBRES,E.APELLIDOS) AS EMPLEADO,C.NOMBRE AS CAPACITACION,S.FECHA_FIN AS FECHA_REFERENCIA,
    'La evaluacion de la capacitacion se encuentra pendiente.' AS MENSAJE
    FROM bbf_capacitacion_participantes P INNER JOIN bbf_empleados E ON E.ID_EMPLEADO=P.ID_EMPLEADO
    INNER JOIN bbf_capacitacion_sesiones S ON S.ID_CAPACITACION_SESION=P.ID_CAPACITACION_SESION
    INNER JOIN bbf_capacitaciones C ON C.ID_CAPACITACION=S.ID_CAPACITACION
    WHERE P.ESTADO_EVALUACION IN('PENDIENTE','EN_PROCESO') AND S.ESTADO<>'ANULADA'
      AND (P_ID_EMPLEADO IS NULL OR P_ID_EMPLEADO=0 OR E.ID_EMPLEADO=P_ID_EMPLEADO)
    UNION ALL
    SELECT 'RESULTADO_NO_APROBADO',P.ID_CAPACITACION_PARTICIPANTE,E.ID_EMPLEADO,E.NUMERO_DOCUMENTO,
    CONCAT_WS(' ',E.NOMBRES,E.APELLIDOS),C.NOMBRE,R.FECHA_RESULTADO,
    CONCAT('Resultado ',R.RESULTADO,'. Puntaje: ',COALESCE(R.PUNTAJE_FINAL,'sin definir'),'.')
    FROM bbf_capacitacion_resultados R INNER JOIN bbf_capacitacion_participantes P ON P.ID_CAPACITACION_PARTICIPANTE=R.ID_CAPACITACION_PARTICIPANTE
    INNER JOIN bbf_empleados E ON E.ID_EMPLEADO=P.ID_EMPLEADO
    INNER JOIN bbf_capacitacion_sesiones S ON S.ID_CAPACITACION_SESION=P.ID_CAPACITACION_SESION
    INNER JOIN bbf_capacitaciones C ON C.ID_CAPACITACION=S.ID_CAPACITACION
    WHERE R.RESULTADO IN('NO_APROBADO','REQUIERE_REINDUCCION')
      AND (P_ID_EMPLEADO IS NULL OR P_ID_EMPLEADO=0 OR E.ID_EMPLEADO=P_ID_EMPLEADO)
    ORDER BY FECHA_REFERENCIA DESC;
END$$


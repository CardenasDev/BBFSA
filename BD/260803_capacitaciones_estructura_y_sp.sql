DELIMITER $$

DROP PROCEDURE IF EXISTS `SP_BBF_VALIDAR_MIGRACION_CAPACITACIONES`$$
CREATE PROCEDURE `SP_BBF_VALIDAR_MIGRACION_CAPACITACIONES`()
BEGIN
    IF DATABASE() <> 'bbf_administrativo' THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Base incorrecta. Ejecute sobre bbf_administrativo.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.TABLES
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'bbf_empleados'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.TABLES
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'bbf_usuarios'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.TABLES
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'bbf_permisos'
    ) THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Faltan tablas base requeridas: empleados, usuarios o permisos.';
    END IF;
END$$

CALL `SP_BBF_VALIDAR_MIGRACION_CAPACITACIONES`()$$
DROP PROCEDURE `SP_BBF_VALIDAR_MIGRACION_CAPACITACIONES`$$

